class Command(BaseCommand):
    help = '설문 문항과 선택지를 DB에 로드 (프론트 mock ID와 동일한 PK 사용)'

    def handle(self, *args, **options):
        if Question.objects.exists():
            self.stdout.write('이미 설문 데이터가 존재합니다. 삭제 후 재실행하려면 --flush 옵션을 사용하세요.')
            return

        q_objs, c_objs = [], []
        for qi, q_data in enumerate(QUESTIONS):
            q_objs.append(Question(pk=qi + 1, question=q_data['question'], order=qi + 1))

        Question.objects.bulk_create(q_objs)

        for qi, q_data in enumerate(QUESTIONS):
            q = Question.objects.get(pk=qi + 1)
            for ci, (text, score) in enumerate(q_data['choices']):
                c_objs.append(Choice(
                    pk=qi * 4 + ci + 1,
                    question=q,
                    text=text,
                    score=score,
                    order=ci + 1,
                ))

        Choice.objects.bulk_create(c_objs)
        self.stdout.write(self.style.SUCCESS(
            f'완료: Question {len(q_objs)}개, Choice {len(c_objs)}개 로드'
        ))
